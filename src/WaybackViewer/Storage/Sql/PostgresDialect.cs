using System.Data.Common;
using Npgsql;

namespace WaybackViewer.Storage.Sql;

/// PostgreSQL. The base class's "ON CONFLICT" syntax is already PostgreSQL's, so only the connection and the schema differ.
public sealed class PostgresDialect : SqlDialect
{
    public override string Name => "Postgres";

    public override DbConnection CreateConnection(string connectionString) => new NpgsqlConnection(connectionString);

    public override IReadOnlyList<string> SchemaStatements { get; } =
    [
        """
        CREATE TABLE IF NOT EXISTS Captures (
            Id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            CaptureTs  TEXT NOT NULL,
            Original   TEXT NOT NULL,
            MimeType   TEXT NOT NULL,
            StatusCode TEXT NOT NULL,
            UNIQUE (CaptureTs, Original))
        """,
        """
        CREATE TABLE IF NOT EXISTS Searches (
            Id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            UrlPrefix   TEXT NOT NULL,
            Filter      TEXT NOT NULL,
            CachedAtUtc BIGINT NOT NULL,
            UNIQUE (UrlPrefix, Filter))
        """,
        "CREATE TABLE IF NOT EXISTS SearchCaptures (SearchId BIGINT NOT NULL, CaptureId BIGINT NOT NULL, PRIMARY KEY (SearchId, CaptureId))",
        "CREATE TABLE IF NOT EXISTS Pages (CaptureId BIGINT PRIMARY KEY, Title TEXT, Description TEXT, FetchedAtUtc BIGINT NOT NULL)",
        "CREATE TABLE IF NOT EXISTS PageText (CaptureId BIGINT PRIMARY KEY, Body TEXT NOT NULL)",
        "CREATE TABLE IF NOT EXISTS PageMetadata (CaptureId BIGINT PRIMARY KEY, Views BIGINT, Likes BIGINT, Shares BIGINT, Comments BIGINT, Score BIGINT, EngagementScore BIGINT, Source TEXT, Author TEXT, PublishedAtUtc BIGINT, Tags TEXT, Confidence DOUBLE PRECISION)",
        // No index on SearchText: LIKE '%x%' cannot use a btree, and long page text would exceed the index row limit.
        "CREATE TABLE IF NOT EXISTS CaptureSearch (CaptureId BIGINT PRIMARY KEY, SearchText TEXT NOT NULL)",
        "CREATE TABLE IF NOT EXISTS PageHtml (CaptureId BIGINT PRIMARY KEY, HtmlGz BYTEA NOT NULL)",
        """
        CREATE TABLE IF NOT EXISTS Operations (
            Id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            UrlPrefix   TEXT NOT NULL,
            Filter      TEXT NOT NULL,
            Kind        INTEGER NOT NULL,
            State       INTEGER NOT NULL,
            CreatedAt   BIGINT NOT NULL,
            UpdatedAt   BIGINT NOT NULL,
            Total       INTEGER NOT NULL,
            Completed   INTEGER NOT NULL,
            Failed      INTEGER NOT NULL,
            Error       TEXT,
            UNIQUE (UrlPrefix, Filter, Kind))
        """,
        "CREATE INDEX IF NOT EXISTS IX_SearchCaptures_CaptureId ON SearchCaptures (CaptureId)",
        "CREATE INDEX IF NOT EXISTS IX_Operations_State ON Operations (State, UpdatedAt)"
    ];
}
